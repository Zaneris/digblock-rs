/// Atlas index of the all-set glyph used for solid quads.
const SOLID_INDEX: u32 = 96;

fn glyph_index(c: u8) -> u32 {
	if (0x20..0x7F).contains(&c) {
		u32::from(c) - 0x20
	} else {
		u32::from(b'?') - 0x20
	}
}

/// Expand the bitmask table to an R8 atlas (0 or 255 per pixel).
pub fn build_atlas() -> Vec<u8> {
	let mut px = vec![0u8; (ATLAS_W * ATLAS_H) as usize];
	let mut blit = |index: u32, rows: &[u8; 8]| {
		let (cx, cy) = (index % ATLAS_COLS, index / ATLAS_COLS);
		for (y, row) in rows.iter().enumerate() {
			for x in 0..8u32 {
				if row >> x & 1 == 1 {
					let px_x = cx * GLYPH_W + x;
					let px_y = cy * GLYPH_H + y as u32;
					px[(px_y * ATLAS_W + px_x) as usize] = 255;
				}
			}
		}
	};
	for (i, rows) in FONT.iter().enumerate() {
		blit(i as u32, rows);
	}
	blit(SOLID_INDEX, &[0xFF; 8]);
	px
}

/// (uv_min, uv_max) of a character's atlas cell.
pub fn glyph_uv(c: u8) -> ([f32; 2], [f32; 2]) {
	cell_uv(glyph_index(c))
}

/// UV at the center of the solid glyph — safe for untextured quads.
pub fn solid_uv() -> [f32; 2] {
	let (min, max) = cell_uv(SOLID_INDEX);
	[(min[0] + max[0]) * 0.5, (min[1] + max[1]) * 0.5]
}

fn cell_uv(index: u32) -> ([f32; 2], [f32; 2]) {
	let (cx, cy) = ((index % ATLAS_COLS) as f32, (index / ATLAS_COLS) as f32);
	let (gw, gh) = (
		GLYPH_W as f32 / ATLAS_W as f32,
		GLYPH_H as f32 / ATLAS_H as f32,
	);
	([cx * gw, cy * gh], [(cx + 1.0) * gw, (cy + 1.0) * gh])
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn printable_glyphs_are_nonempty_and_distinct() {
		for c in 0x21u8..0x7F {
			let g = &FONT[(c - 0x20) as usize];
			assert!(g.iter().any(|&r| r != 0), "glyph {:?} empty", c as char);
		}
		assert_ne!(FONT[(b'A' - 0x20) as usize], FONT[(b'B' - 0x20) as usize]);
	}

	#[test]
	fn atlas_has_solid_glyph() {
		let px = build_atlas();
		let uv = solid_uv();
		let (x, y) = (
			(uv[0] * ATLAS_W as f32) as u32,
			(uv[1] * ATLAS_H as f32) as u32,
		);
		assert_eq!(px[(y * ATLAS_W + x) as usize], 255);
		// Space stays empty.
		assert!(px[0..8].iter().all(|&p| p == 0));
	}
}
